-- Activity catalogue (docs/product "Buddy Club activity catalogue", 2026-10-22).
--   * community.sports becomes the activity table: every trackable thing is a row, with a
--     category_id into community.interests (which keeps the categories);
--   * the catalogue in packages/shared-types/src/catalogue.json is the source; this seed is a
--     one-off copy of it, and scripts/seed-catalogue.ts upserts later edits;
--   * profile activities always name an activity now; the interest-only rows move to the
--     same-named activity; the level check becomes a length check (ladders live in the catalogue);
--   * activity suggestions: what people typed that we do not have yet, with who asked.
-- Additive. Reverse:
--   drop table identity.activity_suggestions;
--   alter table identity.profile_activities drop column custom_name,
--     drop constraint profile_activities_level_length, add constraint profile_activities_level_check
--     check (level in ('just_starting','getting_going','comfortable','strong','expert'));
--   alter table community.sports drop column category_id;
--   (seeded rows stay; ids are never removed)

