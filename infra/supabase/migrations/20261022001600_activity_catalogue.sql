-- Profiles: the activity is the unit. Interest-only rows (walking, books, ...) become the
-- same-named activity; the umbrella interests have no activity and those rows go.
alter table identity.profile_activities
  add column custom_name text check (char_length(custom_name) between 1 and 60);
update identity.profile_activities p
  set sport_id = p.interest_id
  where p.sport_id is null and exists (select 1 from community.sports s where s.id = p.interest_id);
delete from identity.profile_activities where sport_id is null;
alter table identity.profile_activities drop constraint if exists profile_activities_level_check;
alter table identity.profile_activities
  add constraint profile_activities_level_length check (level is null or char_length(level) between 1 and 40);
comment on column identity.profile_activities.level is 'A value from the activity''s ladder in the catalogue; validated by the API';
comment on column identity.profile_activities.custom_name is 'What the person typed when the activity is "other": a suggestion not yet in the catalogue';

-- Suggestions: the promotion queue, made visible as a count.
create table identity.activity_suggestions (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references identity.user_profiles (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 60),
  -- normalised for counting: lowercase, letters and digits, single spaces
  key text not null check (char_length(key) between 1 and 60),
  promoted_to text references community.sports (id),
  created_at timestamptz not null default now(),
  unique (profile_id, key)
);
create index activity_suggestions_key_idx on identity.activity_suggestions (key) where promoted_to is null;
alter table identity.activity_suggestions enable row level security;
